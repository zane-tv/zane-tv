/** Theme-aware image: GitHub swaps <picture> sources with the viewer's color mode. */
function picture(asset: string, alt: string, width?: string): string {
  return (
    `<picture><source media="(prefers-color-scheme: dark)" srcset="assets/${asset}-dark.svg">` +
    `<img src="assets/${asset}-light.svg"${width ? ` width="${width}"` : ""} alt="${esc(alt)}"></picture>`
  );
}

const GENERATED = "<!-- Generated by `bun run build` from src/content.ts. Edit the source, not this file. -->";

/** VietQR block, plus the GitHub Sponsors button once that profile is public. */
function supportBlock(data: ProfileData, account: string): string {
  const block = picture("support", supportAlt(account), "100%");
  if (!data.sponsorsPublic) return block;
  const button = picture("sponsor", `Sponsor ${profile.name} on GitHub`);
  return `${block}\n\n<a href="https://github.com/sponsors/${profile.login}">${button}</a>`;
}

export function readme(data: ProfileData, account: string): string {
  // One paragraph per grid: the inline gap between images is the same across
  // and down, and 2 x 49.3% plus that gap still fits a 320px-wide column.
  const cards = featured.map((p) => {
    const stats = data.repos.get(p.repo)!;
    return `  <a href="https://github.com/${profile.login}/${p.repo}">${picture(`work-${p.repo}`, cardAlt(p, stats), "49.3%")}</a>`;
  });
  const repos = `https://github.com/${profile.login}?tab=repositories`;

  return `${GENERATED}

${picture("hero", heroAlt(data), "100%")}

${picture("roles", rolesAlt(), "100%")}

<p>
${cards.join("\n")}
</p>

<p>
  <a href="${repos}&sort=stargazers">${picture("stats", statsAlt(data), "49.3%")}</a>
  <a href="${repos}">${picture("languages", languagesAlt(data), "49.3%")}</a>
</p>

${picture("activity", activityAlt(data), "100%")}

${profile.lately}

${supportBlock(data, account)}

<details><summary>Copy the account number · Sao chép số tài khoản</summary>

\`${account}\` · ${support.bank.name}

</details>

<sub><a href="${profile.linkedin}">LinkedIn</a> · <a href="mailto:${profile.email}">${profile.email}</a></sub>
`;
}

/**
 * Landing page for the FUNDING.yml link. The profile can't be deep-linked to
 * its support block: images load after the browser resolves the fragment.
 */
export function donatePage(data: ProfileData, account: string): string {
  return `${GENERATED}

${supportBlock(data, account)}

**${support.bank.name}** · \`${account}\` · VietQR / Napas 247

<sub><a href="https://github.com/${profile.login}">github.com/${profile.login}</a></sub>
`;
}
