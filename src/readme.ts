import { cardAlt } from "./card";
import { featured, profile, support } from "./content";
import type { ProfileData } from "./github";
import { heroAlt } from "./hero";
import { esc } from "./svg";
import { supportAlt } from "./support";

/** Theme-aware image: GitHub swaps <picture> sources with the viewer's color mode. */
function picture(asset: string, alt: string, width?: string): string {
  return (
    `<picture><source media="(prefers-color-scheme: dark)" srcset="assets/${asset}-dark.svg">` +
    `<img src="assets/${asset}-light.svg"${width ? ` width="${width}"` : ""} alt="${esc(alt)}"></picture>`
  );
}

export function readme(data: ProfileData, account: string): string {
  // One paragraph: the inline gap between images is the same across and down,
  // and 2 x 49.3% plus that gap still fits a 320px-wide mobile column.
  const cards = featured.map((p) => {
    const stats = data.repos.get(p.repo)!;
    return `  <a href="https://github.com/${profile.login}/${p.repo}">${picture(`work-${p.repo}`, cardAlt(p, stats), "49.3%")}</a>`;
  });

  const sponsor = data.sponsorsPublic
    ? `\n<a href="https://github.com/sponsors/${profile.login}">${picture("sponsor", `Sponsor ${profile.name} on GitHub`)}</a>\n`
    : "";

  return `<!-- Generated by \`bun run build\` from src/content.ts. Edit the source, not this file. -->

${picture("hero", heroAlt(data), "100%")}

<p>
${cards.join("\n")}
</p>

${profile.lately}

<a name="support"></a>

${picture("support", supportAlt(account), "100%")}
${sponsor}
<details><summary>Copy the account number · Sao chép số tài khoản</summary>

\`${account}\` · ${support.bank.name}

</details>

<sub><a href="${profile.linkedin}">LinkedIn</a> · <a href="mailto:${profile.email}">${profile.email}</a></sub>
`;
}
